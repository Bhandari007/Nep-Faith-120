class AuthenticCorpusHarvester:
    """High-throughput parallel harvester collecting verifiable Nepali passages."""

    def __init__(
        self,
        output_file: Path = Path("data/derived/authentic_passages_60.jsonl"),
        max_workers: int = 8,
    ):
        self.output_file = Path(output_file)
        self.output_file.parent.mkdir(parents=True, exist_ok=True)
        self.max_workers = max_workers

    def _fetch_wikipedia_extract(self, title: str, url: str) -> Optional[str]:
        """Fetches authentic introductory lead text from Nepali Wikipedia API."""
        encoded_title = urllib.parse.quote(title)
        api_url = (
            f"https://ne.wikipedia.org/w/api.php?action=query&prop=extracts&exintro=1"
            f"&explaintext=1&titles={encoded_title}&format=json"
        )
        req = urllib.request.Request(api_url, headers={"User-Agent": USER_AGENT})
        try:
            with urllib.request.urlopen(req, timeout=12) as resp:
                data = json.loads(resp.read().decode("utf-8"))
            pages = data.get("query", {}).get("pages", {})
            for _, page in pages.items():
                extract = page.get("extract", "")
                if extract:
                    # Clean brackets and normalize
                    cleaned = re.sub(r"\[\d+\]", "", extract)
                    return normalize_devanagari(cleaned)
        except Exception as e:
            logger.warning(f"Wikipedia fetch failed for {title}: {e}")
        return None

    def process_target(self, idx: int, target: Dict[str, Any]) -> Optional[AuthenticPassage]:
        """Processes a single target specification either via API or verified direct text."""
        domain = target["domain"]
        sub_genre = target["sub_genre"]
        source_type = target.get("source_type", "direct_verbatim")
        source_title = target["title"]
        source_url = target["url"]
        publisher = target.get("publisher", "Wikimedia Foundation" if domain == "wikipedia" else "Official Portal")
        year = target.get("year", 2024)

        passage_text = ""
        if source_type == "wikipedia":
            wiki_text = self._fetch_wikipedia_extract(source_title, source_url)
            if wiki_text and len(wiki_text.strip()) >= 50:
                passage_text = wiki_text
            else:
                # Fallback to direct authentic text if network timeout
                passage_text = target.get("text", "")
        else:
            passage_text = target.get("text", "")

        if not passage_text:
            logger.error(f"Failed to acquire passage text for target {idx}: {source_title}")
            return None

        # Clean and validate Devanagari text
        normalized = normalize_devanagari(passage_text)
        w_count = count_tokens(normalized)

        passage_id = f"auth_{domain[:4]}_{sub_genre[:4]}_{idx:03d}"
        return AuthenticPassage(
            passage_id=passage_id,
            domain=domain,
            sub_genre=sub_genre,
            source_title=source_title,
            source_url=source_url,
            publisher=publisher,
            publication_year=year,
            passage_ne=normalized,
            word_count=w_count,
        )

    def harvest_targets(self, targets: List[Dict[str, Any]]) -> List[AuthenticPassage]:
        """Harvests a list of targets in parallel using ThreadPoolExecutor."""
        assert "data/raw/labels" not in str(self.output_file), "PROHIBITION: Cannot write to gold label path"

        results: List[AuthenticPassage] = []
        logger.info(f"Starting parallel harvest of {len(targets)} authentic targets with {self.max_workers} workers...")

        with ThreadPoolExecutor(max_workers=self.max_workers) as executor:
            future_to_idx = {
                executor.submit(self.process_target, idx, target): idx
                for idx, target in enumerate(targets, start=1)
            }
            for future in as_completed(future_to_idx):
                idx = future_to_idx[future]
                try:
                    res = future.result()
                    if res:
                        results.append(res)
                except Exception as e:
                    logger.error(f"Error processing target #{idx}: {e}")

        # Sort results deterministically by passage_id
        results.sort(key=lambda x: x.passage_id)

        # Write to JSONL
        with open(self.output_file, "w", encoding="utf-8") as f:
            for p in results:
                f.write(json.dumps(asdict(p), ensure_ascii=False) + "\n")

        logger.info(f"Successfully harvested {len(results)} authentic passages into {self.output_file}")
        return results

    def harvest_all(self) -> List[AuthenticPassage]:
        return self.harvest_targets(HARVEST_TARGETS)


